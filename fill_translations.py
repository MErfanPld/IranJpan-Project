def fill(po_path, translations):
    po = polib.pofile(po_path)
    filled, missing = 0, []
    for entry in po:
        if entry.msgid in translations:
            entry.msgstr = translations[entry.msgid]
            filled += 1
        elif not entry.msgstr:
            missing.append(entry.msgid)
    po.save(po_path)
    print(f"{po_path}: {filled} پر شد, {len(missing)} پیدا نشد")
    if missing:
        print("  متن‌های بدون ترجمه (باید دستی اضافه کنی):")
        for m in missing:
            print(f"    - {m!r}")


